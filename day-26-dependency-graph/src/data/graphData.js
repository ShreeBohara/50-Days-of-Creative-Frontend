export function createLinks(nodes = initialNodes) {
  const nodeIds = new Set(nodes.map((node) => node.id))

  return nodes.flatMap((node) =>
    node.dependencies
      .filter((dependencyId) => nodeIds.has(dependencyId))
      .map((dependencyId) => ({
        id: `${node.id}->${dependencyId}`,
        source: node.id,
        target: dependencyId,
        relationship: 'depends on',
      })),
  )
}

export function withDependents(nodes = initialNodes, links = createLinks(nodes)) {
  const dependentCounts = links.reduce((counts, link) => {
    counts.set(link.target, (counts.get(link.target) ?? 0) + 1)
    return counts
  }, new Map())

  return nodes.map((node) => ({
    ...node,
    dependentCount: dependentCounts.get(node.id) ?? 0,
    dependencyCount: node.dependencies.length,
    expanded: Boolean(node.expanded),
  }))
}

export function createGraphData(nodes = initialNodes) {
  const links = createLinks(nodes)

  return {
    nodes: withDependents(nodes, links),
    links,
  }
}
